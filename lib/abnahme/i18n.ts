export function formatDatumZeit(iso: string | null | undefined, sprache: Sprache): string {
  if (!iso) return "";
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toLocaleString(sprache === "en" ? "en-GB" : "de-DE", { dateStyle: "medium", timeStyle: "short" });
}

export function formatDatum(iso: string | null | undefined, sprache: Sprache): string {
  if (!iso) return "";
  const d = new Date(iso.length === 10 ? `${iso}T12:00:00` : iso);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toLocaleDateString(sprache === "en" ? "en-GB" : "de-DE", { dateStyle: "medium" });
}
